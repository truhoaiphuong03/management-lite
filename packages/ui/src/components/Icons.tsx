/**
 * Helper component to render an icon for a navigation item by its id.
 */
export const NavIcon: React.FC<{ id: string; size?: number }> = ({
  id,
  size = 18,
}) => {
  switch (id) {
    case 'dashboard':
      return <LayoutDashboardIcon size={size} />;
    case 'clock':
      return <ClockIcon size={size} />;
    case 'schedule':
      return <CalendarIcon size={size} />;
    case 'reports':
      return <FileTextIcon size={size} />;
    case 'work':
      return <ClipboardListIcon size={size} />;
    case 'attendance':
      return <CalendarIcon size={size} />;
    case 'attendance-review':
      return <CheckCircleIcon size={size} />;
    case 'employees':
      return <UsersIcon size={size} />;
    case 'payroll':
    case 'my-pay':
    case 'finance':
      return <BanknoteIcon size={size} />;
    case 'system-logs':
      return <ShieldAlertIcon size={size} />;
    case 'accounts':
      return <LockIcon size={size} />;
    case 'audit':
      return <ClipboardListIcon size={size} />;
    case 'settings':
      return <SettingsIcon size={size} />;
    case 'storage':
      return <FileTextIcon size={size} />;
    case 'issues':
      return <AlertTriangleIcon size={size} />;
    default:
      return <FileTextIcon size={size} />;
  }
};
